
import json
from pathlib import Path

from flask import sessions
import pandas as pd

from src.generator import (
    generate_customers,
    generate_sessions,
    generate_events,
     generate_pages,
    generate_products,
)
from src.pipeline import run_validation


def main():
    # Resolve project directories.
    project_root = Path(__file__).resolve().parent
    config_path = project_root / "config" / "config.json"
    raw_dir = project_root / "data" / "raw"
    raw_dir.mkdir(parents=True, exist_ok=True)

    # Load configuration
    with open(config_path, "r", encoding="utf-8") as file:
        config = json.load(file)

    seed = config["seed"]
    customer_count = config["customer_count"]
    session_count = config["session_count"]
    pages = generate_pages()
    products = generate_products(
    product_count=20,
    seed=seed,
    )

    # Generate synthetic data.
    customers = generate_customers(customer_count, seed=seed)
    sessions = generate_sessions(customers, session_count, seed=seed)
    events = generate_events(
        sessions,
        pages=pages,
        products=products,
        seed=seed,
    )
    # Convert records into DataFrames.
    customers_df = pd.DataFrame(customers)
    sessions_df = pd.DataFrame(sessions)
    events_df = pd.DataFrame(events)

    pages_df = pd.DataFrame(pages)
    products_df = pd.DataFrame(products)

    # Save raw datasets.
    customers_df.to_csv(raw_dir / "customers.csv", index=False)
    sessions_df.to_csv(raw_dir / "sessions.csv", index=False)
    events_df.to_csv(raw_dir / "journey_events.csv", index=False)
    pages_df.to_csv(raw_dir / "pages.csv", index=False)
    products_df.to_csv(raw_dir / "products.csv", index=False)

    # Save a run manifest.
    manifest = {
        "seed": seed,
        "customer_count": len(customers),
        "session_count": len(sessions),
        "event_count": len(events),
        "page_count": len(pages),
        "product_count": len(products),
        "files": [
            "customers.csv",
            "sessions.csv",
            "journey_events.csv",
            "pages.csv",
            "products.csv",
        ],
    }

    with open(raw_dir / "manifest.json", "w", encoding="utf-8") as file:
        json.dump(manifest, file, indent=2)

    print("Raw data generation complete.")
    print(f"Output directory: {raw_dir}")
    print(f"Customers: {len(customers_df)}")
    print(f"Sessions: {len(sessions_df)}")
    print(f"Events: {len(events_df)}")

    # Run validation, standardization, and analytics.
    results = run_validation(project_root)

    print("\nValidation summary")
    for dataset, (total, valid, invalid) in results.items():
        print(
            f"{dataset}: total={total}, "
            f"valid={valid}, quarantined={invalid}"
        )

    # Display the curated metrics generated by the pipeline.
    metrics_path = (
        project_root / "data" / "curated" / "journey_metrics.csv"
    )

    if metrics_path.exists():
        metrics = pd.read_csv(metrics_path)
        print("\nJourney metrics:")
        print(metrics.to_string(index=False))
    else:
        print("\nWarning: journey_metrics.csv was not generated.")

    print(f"Pages: {len(pages_df)}")
    print(f"Products: {len(products_df)}")

if __name__ == "__main__":
    main()
